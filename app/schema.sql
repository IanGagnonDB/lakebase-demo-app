-- Created by the app service principal, which therefore owns these tables.
-- Lakebase CDF replicates schema `app` to the UC bronze schema.
CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE IF NOT EXISTS app.opportunities (
  opportunity_id bigint PRIMARY KEY,
  account_id     bigint NOT NULL,
  rep_id         integer NOT NULL,
  name           text NOT NULL,
  service_line   text NOT NULL,
  stage          text NOT NULL,
  amount         numeric(12,2) NOT NULL,
  close_date     date NOT NULL,
  updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.activities (
  activity_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rep_id         integer NOT NULL,
  account_id     bigint NOT NULL,
  activity_type  text NOT NULL,
  activity_ts    timestamptz NOT NULL DEFAULT now(),
  notes          text
);

CREATE INDEX IF NOT EXISTS activities_rep_ts   ON app.activities (rep_id, activity_ts DESC);
CREATE INDEX IF NOT EXISTS opportunities_rep   ON app.opportunities (rep_id);
CREATE INDEX IF NOT EXISTS opportunities_stage ON app.opportunities (stage);

ALTER TABLE app.opportunities REPLICA IDENTITY FULL;  -- Lakebase CDF requirement
ALTER TABLE app.activities    REPLICA IDENTITY FULL;
